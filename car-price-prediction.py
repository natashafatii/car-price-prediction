import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import r2_score, mean_absolute_error, mean_squared_error
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.compose import ColumnTransformer

numeric_cols = ['model_year', 'engine_size', 'mileage', 'owner_count']
categorical_cols = ['brand', 'fuel_type', 'transmission']

# Preprocessing: encode categorical + scale numeric
encoder = OneHotEncoder(handle_unknown='ignore', sparse_output=False)
scaler = StandardScaler()

preprocessor = ColumnTransformer([
    ('encode', encoder, categorical_cols),
    ('scale', scaler, numeric_cols)
])

# 4.1 Feature-Target Split
X = df.drop('price', axis=1)
y = df['price']

# Apply preprocessing
X_processed = preprocessor.fit_transform(X)

# 4.2 Train-Test Split (80% train, 20% test)
X_train, X_test, y_train, y_test = train_test_split(X_processed, y, test_size=0.2, random_state=42)

# 4.3 Train Regression Models
# Linear Regression
lr_model = LinearRegression()
lr_model.fit(X_train, y_train)

# Random Forest Regressor
rf_model = RandomForestRegressor(n_estimators=100, random_state=42)
rf_model.fit(X_train, y_train)

# Optional: You can train Gradient Boosting or XGBoost here if desired
# from sklearn.ensemble import GradientBoostingRegressor
# gb_model = GradientBoostingRegressor(n_estimators=100, learning_rate=0.1, random_state=42)
# gb_model.fit(X_train, y_train)

# 4.4 Evaluate Each Model
models = {'Linear Regression': lr_model, 'Random Forest': rf_model}

for name, model in models.items():
    y_pred = model.predict(X_test)
    print(f"\n{name} Evaluation:")
    print(f"R² Score: {r2_score(y_test, y_pred):.3f}")
    print(f"Mean Absolute Error (MAE): {mean_absolute_error(y_test, y_pred):.2f}")
    print(f"Mean Squared Error (MSE): {mean_squared_error(y_test, y_pred):.2f}")
    rmse = np.sqrt(mean_squared_error(y_test, y_pred))  # RMSE calculation
    print(f"Root Mean Squared Error (RMSE): {rmse:.2f}")

